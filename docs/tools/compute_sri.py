"""Download the pinned CDN files and write their Subresource Integrity hashes to sri.toml.

Run this by hand when you change a pinned version in PINNED below:

    uv run --group docs python docs/tools/compute_sri.py

The hash is sha384 over the exact bytes jsDelivr serves, base64-encoded, which is what the
``integrity`` attribute expects. pagebase.py reads sri.toml; nothing at build time touches
the network.
"""

import base64
import hashlib
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent

# key -> path under https://cdn.jsdelivr.net/
PINNED = {
    "bootstrap_css": "npm/bootstrap@5.3.3/dist/css/bootstrap.min.css",
    "bootstrap_js": "npm/bootstrap@5.3.3/dist/js/bootstrap.bundle.min.js",
    "mermaid_js": "npm/mermaid@11.4.1/dist/mermaid.min.js",
}


def sri(data: bytes) -> str:
    return "sha384-" + base64.b64encode(hashlib.sha384(data).digest()).decode("ascii")


def main() -> None:
    lines = ["# Generated by compute_sri.py. Do not edit by hand.", ""]
    for key, path in PINNED.items():
        url = "https://cdn.jsdelivr.net/" + path
        with urllib.request.urlopen(url, timeout=60) as resp:  # noqa: S310
            data = resp.read()
        lines += [
            f"[{key}]",
            f'url = "{url}"',
            f'integrity = "{sri(data)}"  # pragma: allowlist secret',
            "",
        ]
        print(f"{key}: {sri(data)}")
    (HERE / "sri.toml").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
